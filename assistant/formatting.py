"""Разметка исходящих сообщений — жирный текст в Telegram.

Зачем это есть. Раньше бот слал всё обычным текстом, без parse_mode.
Значит `**Проф деятельность:**` доезжало до Кати ровно так, со звёздочками
— и в шеринге это выглядело мусором. Поэтому в промпте стояло «без
маркдаун-звёздочек», а Катя 25 августа попросила обратное: чтобы названия
блоков в её вечернем чистовике были жирными, как в её собственном формате.

Почему HTML, а не Markdown. У Telegram три режима:
  Markdown (legacy) — ломается на любом одиночном `_`, `*`, `[` в тексте,
  MarkdownV2 — требует экранировать полтора десятка знаков, включая `.`,
                `-`, `!`, `(`, `)`, а у Кати в шерингах и тире, и проценты,
                и скобки, и кавычки-ёлочки,
  HTML — экранировать надо ровно три символа: & < >.
Берём HTML: он единственный, где живой русский текст не надо калечить.

Модель по-прежнему пишет привычными звёздочками — их превращаем в <b>
здесь, уже после экранирования. Так текст Кати не может случайно стать
разметкой, а разметка не может развалить текст.
"""

import html
import logging
import re

logger = logging.getLogger(__name__)

# Жирный — только в пределах одной строки. Без re.DOTALL сознательно:
# если модель поставит непарную звёздочку, испортится максимум эта строка,
# а не весь шеринг ниже по тексту.
_BOLD = re.compile(r"\*\*(.+?)\*\*")

# Лимит Telegram — 4096 символов. Берём с запасом: экранирование удлиняет
# текст (& → &amp;), и теги <b></b> тоже занимают место.
CHUNK_LIMIT = 3500


# ── Английские буквы внутри русских слов ─────────────────────────────
#
# Катя поймала это 21 сентября: «она начинает иногда использовать
# английский алфавит в русском тексте». Замер по переписке 9–21 сентября:
# одно слово на 71 сообщение. Примеры и что в них на самом деле:
#
#   «совсem»        — e, m латиницей. Буквы неотличимы от русских.
#   «beспокоишься»  — b, e латиницей.
#   «dizайнер»      — d, i, z латиницей. А вот это уже НЕ похожие буквы:
#                     модель соскользнула на английскую раскладку посреди
#                     слова. Поэтому чиним не «похожие буквы», а любые
#                     латинские внутри русского слова.
#
# Глазами такое слово выглядит нормально, но для поиска его не существует:
# ни Катя не найдёт его в переписке, ни Анджелина в своём архиве. Ради
# поиска всё и затевалось — «dizайнер» уже лежит в базе, в шеринге за 14-е.
#
# Правило намеренно узкое: слово трогаем, только если в нём есть и русские,
# и латинские буквы И РУССКИХ БОЛЬШЕ. Чисто английские слова (Reels,
# Threads, AI, Sorry) не содержат ни одной русской буквы — их не касаемся.
# Дефис разрывает слово, поэтому «AI-бот» и «Flam-мероприятие» целы.
#
# ⚠️ Перевод неоднозначен для пары букв: латинская «p» — это и русская «р»
# (буквы неотличимы), и «п» (по звуку). Выбрана «р»: совпадение начертаний
# встречается чаще, чем транслитерация. Поэтому КАЖДАЯ замена пишется в
# лог — через неделю посмотреть, не портит ли правило живые слова.
_LAT_TO_CYR = str.maketrans({
    "a": "а", "b": "б", "c": "с", "d": "д", "e": "е", "f": "ф", "g": "г",
    "h": "х", "i": "и", "j": "й", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "р", "q": "к", "r": "р", "s": "с", "t": "т", "u": "у",
    "v": "в", "w": "в", "x": "х", "y": "у", "z": "з",
    "A": "А", "B": "В", "C": "С", "D": "Д", "E": "Е", "F": "Ф", "G": "Г",
    "H": "Н", "I": "И", "J": "Й", "K": "К", "L": "Л", "M": "М", "N": "Н",
    "O": "О", "P": "Р", "Q": "К", "R": "Р", "S": "С", "T": "Т", "U": "У",
    "V": "В", "W": "В", "X": "Х", "Y": "У", "Z": "З",
})

_WORD = re.compile(r"[A-Za-zА-Яа-яЁё]+")
_CYR = re.compile(r"[А-Яа-яЁё]")
_LAT = re.compile(r"[A-Za-z]")


def fix_latin_in_russian(text: str) -> str:
    """Вернуть латинские буквы, затесавшиеся в русские слова, обратно."""
    if not text:
        return text

    fixes: list[str] = []

    def repair(match: re.Match) -> str:
        word = match.group(0)
        lat = len(_LAT.findall(word))
        if not lat:
            return word
        cyr = len(_CYR.findall(word))
        if cyr <= lat:  # чисто английское или больше чем наполовину — не наше
            return word
        fixed = word.translate(_LAT_TO_CYR)
        fixes.append(f"{word} → {fixed}")
        return fixed

    result = _WORD.sub(repair, text)
    if fixes:
        logger.info("латиница в русских словах, исправлено: %s", "; ".join(fixes))
    return result


def to_html(text: str) -> str:
    """Экранировать текст и превратить **звёздочки** в настоящий жирный."""
    escaped = html.escape(text, quote=False)
    return _BOLD.sub(lambda m: f"<b>{m.group(1)}</b>", escaped)


def split_chunks(text: str, limit: int = CHUNK_LIMIT) -> list[str]:
    """Разбить длинный ответ на куски, по возможности по переносам строк.

    Режем ДО экранирования и по границам строк — чтобы `**заголовок**` не
    разорвался пополам между двумя сообщениями и не осыпался звёздочками.
    """
    if len(text) <= limit:
        return [text]

    chunks: list[str] = []
    current = ""
    for line in text.splitlines(keepends=True):
        # Одна строка длиннее лимита — режем её как есть, деваться некуда.
        while len(line) > limit:
            if current:
                chunks.append(current)
                current = ""
            chunks.append(line[:limit])
            line = line[limit:]
        if len(current) + len(line) > limit:
            chunks.append(current)
            current = line
        else:
            current += line
    if current:
        chunks.append(current)
    return chunks

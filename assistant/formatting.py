"""Разметка исходящих сообщений — жирный текст в Telegram.

Зачем это есть. Раньше бот слал всё обычным текстом, без parse_mode.
Значит `**Проф деятельность:**` доезжало до Кати ровно так, со звёздочками
— и в шеринге это выглядело мусором. Поэтому в промпте стояло «без
маркдаун-звёздочек», а Катя 25 августа попросила обратное: чтобы названия
блоков в её вечернем чистовике были жирными, как в её собственном формате.

Почему HTML, а не Markdown. У Telegram три режима:
  Markdown (legacy) — ломается на любом одиночном `_`, `*`, `[` в тексте,
  MarkdownV2 — требует экранировать полтора десятка знаков, включая `.`,
                `-`, `!`, `(`, `)`, а у Кати в шерингах и тире, и проценты,
                и скобки, и кавычки-ёлочки,
  HTML — экранировать надо ровно три символа: & < >.
Берём HTML: он единственный, где живой русский текст не надо калечить.

Модель по-прежнему пишет привычными звёздочками — их превращаем в <b>
здесь, уже после экранирования. Так текст Кати не может случайно стать
разметкой, а разметка не может развалить текст.
"""

import html
import re

# Жирный — только в пределах одной строки. Без re.DOTALL сознательно:
# если модель поставит непарную звёздочку, испортится максимум эта строка,
# а не весь шеринг ниже по тексту.
_BOLD = re.compile(r"\*\*(.+?)\*\*")

# Лимит Telegram — 4096 символов. Берём с запасом: экранирование удлиняет
# текст (& → &amp;), и теги <b></b> тоже занимают место.
CHUNK_LIMIT = 3500


def to_html(text: str) -> str:
    """Экранировать текст и превратить **звёздочки** в настоящий жирный."""
    escaped = html.escape(text, quote=False)
    return _BOLD.sub(lambda m: f"<b>{m.group(1)}</b>", escaped)


def split_chunks(text: str, limit: int = CHUNK_LIMIT) -> list[str]:
    """Разбить длинный ответ на куски, по возможности по переносам строк.

    Режем ДО экранирования и по границам строк — чтобы `**заголовок**` не
    разорвался пополам между двумя сообщениями и не осыпался звёздочками.
    """
    if len(text) <= limit:
        return [text]

    chunks: list[str] = []
    current = ""
    for line in text.splitlines(keepends=True):
        # Одна строка длиннее лимита — режем её как есть, деваться некуда.
        while len(line) > limit:
            if current:
                chunks.append(current)
                current = ""
            chunks.append(line[:limit])
            line = line[limit:]
        if len(current) + len(line) > limit:
            chunks.append(current)
            current = line
        else:
            current += line
    if current:
        chunks.append(current)
    return chunks
